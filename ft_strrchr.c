#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	char	*ls;

	ls = NULL;
	while (*s)
	{
		if (*s == (char)c)
			ls = (char *)s;
		s++;
	}
	if ((char)c == '\0')
		return ((char *)s);
	return (ls);
}
